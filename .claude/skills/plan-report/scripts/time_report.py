#!/usr/bin/env python3
"""Estimate against tracked time for issues closed in a period, and the timeslices that need fixing.

    report.py                         # issues closed today (local time), this repo
    report.py --since 2026-10-01 --hours-per-point 1.0
    report.py --json

Reads GitHub through `gh` and Timewarrior through `timew export`. Writes nothing: correction
commands are printed for Peter to run. Tags follow tt: `owner/repo#N`, `repo:owner/repo`.
Format: gh-plan design 0002 §8 (`plan report time`), which this stands in for until it ships.
"""

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import date, datetime, time, timedelta, timezone
from pathlib import Path

TITLE_ESTIMATE = re.compile(r"^\[(\d+)\]")
LONG_INTERVAL = timedelta(hours=4)
WILD_VARIANCE = 0.5
FLAP_SLICE = timedelta(minutes=3)
FLAP_RUN = 4  # |actual/est - 1| beyond this is called out as a likely tagging problem


@dataclass
class Interval:
    id: int  # timew's @id: 1 is the newest, and ids shift as intervals are added
    start: datetime
    end: datetime | None
    tags: set[str]

    def seconds(self, now: datetime) -> float:
        return ((self.end or now) - self.start).total_seconds()


@dataclass
class Fix:
    interval: Interval
    add: str | None  # tag to add; None means no automatic fix
    remove: str | None
    reason: str


def fix_script(fixes: list[Fix]) -> str:
    """A bash script that retags by @id, refusing to run if any @id now points at another interval."""

    def q(t):
        return "'" + t.replace("'", "'\\''") + "'"

    lines = [
        "#!/usr/bin/env bash",
        "# Generated by plan-report. Review, then run with bash.",
        "set -euo pipefail",
        "",
        "# Timewarrior @ids shift as intervals are added: check each one still starts where it did.",
        'check() { got=$(timew export "@$1" | python3 -c \'import json,sys; print(json.load(sys.stdin)[0]["start"])\')',
        '  [ "$got" = "$2" ] || { echo "@$1 now starts $got, expected $2; rerun the report" >&2; exit 1; }; }',
        "",
    ]
    runnable = [f for f in fixes if f.add]
    for f in runnable:
        lines.append(f"check {f.interval.id} {f.interval.start.strftime('%Y%m%dT%H%M%SZ')}")
    lines.append("")
    for f in runnable:
        lines.append(f"# @{f.interval.id} {hhmm(f.interval.start)}: {f.reason}")
        if f.remove:
            lines.append(f"timew untag @{f.interval.id} {q(f.remove)}")
        lines.append(f"timew tag @{f.interval.id} {q(f.add)}")
    lines.append('echo "retagged ' + str(len(runnable)) + ' intervals"')
    return "\n".join(lines) + "\n"


@dataclass
class Row:
    number: int
    title: str
    estimate: int | None
    closed_at: datetime
    seconds: float = 0.0
    entries: int = 0
    running: int = 0
    notes: list[str] = field(default_factory=list)


def utc(s: str) -> datetime:
    return datetime.strptime(s, "%Y%m%dT%H%M%SZ").replace(tzinfo=timezone.utc)


def parse_intervals(export: list[dict]) -> list[Interval]:
    return [
        Interval(
            e["id"], utc(e["start"]), utc(e["end"]) if "end" in e else None, set(e.get("tags", []))
        )
        for e in export
    ]


def local_day_bounds(since: date, until: date) -> tuple[datetime, datetime]:
    tz = datetime.now().astimezone().tzinfo
    return (
        datetime.combine(since, time.min, tz).astimezone(timezone.utc),
        datetime.combine(until + timedelta(days=1), time.min, tz).astimezone(timezone.utc),
    )


def hhmm(dt: datetime) -> str:
    return dt.astimezone().strftime("%m-%d %H:%M")


def build(
    issues: list[dict],
    intervals: list[Interval],
    slug: str,
    start: datetime,
    end: datetime,
    now: datetime,
    assign: int | None = None,
    move_from: tuple[int, ...] = (),
) -> tuple[list[Row], int, list[str], list[str]]:
    """Rows, the count left out as not planned, discrepancies, and correction commands."""
    tag = f"{slug}#"
    mine = [
        i for i in intervals if f"repo:{slug}" in i.tags or any(t.startswith(tag) for t in i.tags)
    ]
    closed = {i["number"]: i for i in issues}

    rows, not_planned = [], 0
    for issue in sorted(issues, key=lambda i: i["closedAt"]):
        closed_at = datetime.fromisoformat(issue["closedAt"].replace("Z", "+00:00"))
        if not (start <= closed_at < end):
            continue
        if issue.get("stateReason") == "NOT_PLANNED":
            not_planned += 1
            continue
        m = TITLE_ESTIMATE.match(issue["title"])
        row = Row(
            issue["number"],
            TITLE_ESTIMATE.sub("", issue["title"]).strip(),
            int(m[1]) if m else None,
            closed_at,
        )
        for i in mine:
            if f"{tag}{row.number}" in i.tags:
                if i.end is None:
                    row.running += 1
                else:
                    row.seconds += i.seconds(now)
                    row.entries += 1
        rows.append(row)

    found, fixes = [], []

    in_period = [i for i in mine if (i.end or now) > start and i.start < end]
    for i in in_period:
        issue_tags = sorted(t for t in i.tags if t.startswith(tag))
        for n in move_from:
            if assign and f"{tag}{n}" in i.tags and i.end is not None:
                fixes.append(
                    Fix(i, f"{tag}{assign}", f"{tag}{n}", f"tagged #{n}; moved to #{assign}")
                )
        for t in issue_tags:
            n = int(t[len(tag) :])
            issue = closed.get(n)
            if issue is None:
                continue
            closed_at = datetime.fromisoformat(issue["closedAt"].replace("Z", "+00:00"))
            # A GitHub issue's close, while tt's #N is Redmine's: unverified, so no stop is suggested.
            if i.end is None:
                found.append(
                    f"@{i.id} is still running, tagged #{n}; GitHub #{n} closed {hhmm(closed_at)} (unverified: Redmine's #{n} may be open)"
                )
            elif i.start >= closed_at:
                found.append(
                    f"@{i.id} {hhmm(i.start)}–{hhmm(i.end)} is tagged #{n} but starts after GitHub #{n} closed {hhmm(closed_at)} (unverified: Redmine's #{n} may be open)"
                )
                # Assigned to the issue it already carries: the slice is accepted as it is.
                if assign and assign != n and n not in move_from:
                    fixes.append(
                        Fix(i, f"{tag}{assign}", t, f"after #{n} closed; assigned to #{assign}")
                    )
        if len(issue_tags) > 1:
            found.append(
                f"@{i.id} {hhmm(i.start)} carries {len(issue_tags)} issue tags ({', '.join(issue_tags)}); it counts toward each"
            )
        if i.end and i.end - i.start > LONG_INTERVAL:
            found.append(
                f"@{i.id} {hhmm(i.start)}–{hhmm(i.end)} runs {(i.end - i.start).total_seconds() / 3600:.1f} h; check for a timer left on"
            )

    # Untagged slices inside the period: time on main, or before a branch existed.
    ordered = sorted(mine, key=lambda i: i.start)
    for k, i in enumerate(ordered):
        if any(t.startswith(tag) for t in i.tags):
            continue
        stop = i.end or now
        if stop <= start or i.start >= end:
            continue
        guess = None
        # The issue worked next is the usual owner of time spent before its branch.
        for j in ordered[k + 1 :]:
            if nums := [t for t in j.tags if t.startswith(tag)]:
                guess = nums[0]
                break
        mins = (stop - i.start).total_seconds() / 60
        span = f"{hhmm(i.start)} running" if i.end is None else f"{hhmm(i.start)}–{hhmm(i.end)}"
        found.append(f"@{i.id} {span} ({mins:.0f} min) has no issue tag")
        if assign:
            fixes.append(Fix(i, f"{tag}{assign}", None, f"untagged; assigned to #{assign}"))
        elif guess:
            fixes.append(
                Fix(
                    i,
                    guess,
                    None,
                    f"untagged; guess #{guess.rsplit('#', 1)[1]}, the next issue worked",
                )
            )

    # Flapping: the tag switching on and off every few minutes means two signals disagree about
    # where you are (tt's zsh, claude and editor beats pointing at different directories).
    def flap(run):
        if len(run) < FLAP_RUN:
            return
        labels = []
        for i in run:
            nums = sorted(t[len(tag) - 1 :] for t in i.tags if t.startswith(tag))
            label = ", ".join(nums) or "untagged"
            if label not in labels:
                labels.append(label)
        found.append(
            f"@{run[0].id}–@{run[-1].id} {hhmm(run[0].start)}–{hhmm(run[-1].end)}: flapping between "
            f"{' ↔ '.join(labels)} ({len(run)} slices of {FLAP_SLICE.seconds // 60} min or less). Usually two "
            f"checkouts of the repo, e.g. a worktree on one branch and the main checkout on another, "
            f"both sending signals"
        )

    run = []
    for i in sorted(in_period, key=lambda i: i.start):
        if i.end and i.end - i.start <= FLAP_SLICE:
            run.append(i)
            continue
        flap(run)
        run = []
    flap(run)

    for r in rows:
        if r.entries == 0 and r.running == 0:
            found.append(f"#{r.number} closed with no tagged time")
    return rows, not_planned, found, fixes


def render(rows: list[Row], not_planned: int, hpp: float, hpp_source: str) -> str:
    out = ["#      est  est h   actual h   variance"]
    tot_pts = tot_act = 0.0
    with_snap = 0
    for r in rows:
        est_h = r.estimate * hpp if r.estimate else None
        if r.entries == 0:
            why = f"no snapshot ({r.running} entry still running)" if r.running else "no snapshot"
            out.append(
                f"#{r.number:<5} {r.estimate or '—':>3}  {est_h if est_h is not None else '—':>5}       —          {why}"
            )
            continue
        act = r.seconds / 3600
        if est_h:
            var = act - est_h
            flag = "  ← check tagging" if abs(act / est_h - 1) > WILD_VARIANCE else ""
            out.append(
                f"#{r.number:<5} {r.estimate:>3}  {est_h:>5.1f}    {act:>5.2f}    {var:>+6.2f}  {var / est_h:>+5.0%}{flag}"
            )
            tot_pts += r.estimate
            tot_act += act
            with_snap += 1
        else:
            out.append(f"#{r.number:<5}   —      —    {act:>5.2f}          no estimate")
    out.append("───")
    if tot_pts:
        var = tot_act - tot_pts * hpp
        out.append(
            f"       {tot_pts:>3.0f}  {tot_pts * hpp:>5.1f}    {tot_act:>5.2f}    {var:>+6.2f}  {var / (tot_pts * hpp):>+5.0%}"
            f"     ({with_snap} of {len(rows)} items with a snapshot)"
        )
        out.append(
            f"hours per point: configured {hpp:g} ({hpp_source}) · observed {tot_act / tot_pts:.2f}"
        )
    else:
        out.append(f"no items with both an estimate and tracked time ({len(rows)} closed)")
    if not_planned:
        out.append(f"{not_planned} closed as not planned, left out")
    return "\n".join(out)


def hours_per_point(flag: float | None) -> tuple[float, str]:
    if flag is not None:
        return flag, "--hours-per-point"
    return 8.0, "default; pass --hours-per-point"


def run_json(cmd: list[str]):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"{' '.join(cmd)} failed: {r.stderr.strip()}")
    return json.loads(r.stdout or "[]")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument(
        "--since", type=date.fromisoformat, default=date.today(), help="local date, default today"
    )
    p.add_argument(
        "--until", type=date.fromisoformat, help="local date, inclusive; default --since"
    )
    p.add_argument("--repo", help="owner/name; default this repo")
    p.add_argument("--hours-per-point", type=float)
    p.add_argument("--json", action="store_true")
    p.add_argument(
        "--assign",
        type=int,
        metavar="N",
        help="retag untagged slices, and slices tagged an issue after it closed, to #N",
    )
    p.add_argument(
        "--from",
        dest="move_from",
        type=int,
        action="append",
        default=[],
        metavar="N",
        help="with --assign: also move every closed slice in the period tagged #N to the assigned issue",
    )
    p.add_argument(
        "--fix-script",
        type=Path,
        metavar="PATH",
        help="write the corrections as a guarded bash script",
    )
    a = p.parse_args(argv)
    # Redmine's issue numbers clash with GitHub's, so a tag this reads as a closed GitHub issue may
    # be right for Redmine's, and a retag would overwrite it.
    if a.assign or a.move_from:
        p.error(
            "--assign and --from are off until plan-report reads Redmine: the two trackers share issue numbers"
        )

    slug = a.repo or run_json(["gh", "repo", "view", "--json", "nameWithOwner"])["nameWithOwner"]
    start, end = local_day_bounds(a.since, a.until or a.since)
    issues = run_json(
        [
            "gh",
            "issue",
            "list",
            "--repo",
            slug,
            "--state",
            "closed",
            "--limit",
            "1000",
            "--search",
            f"closed:>={(a.since - timedelta(days=1)).isoformat()}",
            "--json",
            "number,title,closedAt,stateReason",
        ]
    )
    intervals = parse_intervals(run_json(["timew", "export"]))
    now = datetime.now(timezone.utc)
    hpp, source = hours_per_point(a.hours_per_point)
    rows, not_planned, found, fixes = build(
        issues, intervals, slug, start, end, now, a.assign, tuple(a.move_from)
    )

    if a.json:
        print(
            json.dumps(
                {
                    "repo": slug,
                    "since": a.since.isoformat(),
                    "hours_per_point": hpp,
                    "rows": [r.__dict__ | {"closed_at": r.closed_at.isoformat()} for r in rows],
                    "not_planned": not_planned,
                    "discrepancies": found,
                    "corrections": [f"@{f.interval.id}: {f.reason}" for f in fixes],
                },
                indent=2,
                default=str,
            )
        )
        return 0
    period = a.since.isoformat() + (f" to {a.until.isoformat()}" if a.until else "")
    print(f"{slug} · closed {period}\n")
    print(render(rows, not_planned, hpp, source))
    if found:
        print(f"\nTimeslices to check ({len(found)}):")
        print("\n".join(f"  - {f}" for f in found))
    if fixes:
        print(f"\nCorrections ({len(fixes)}):")
        print("\n".join(f"  @{f.interval.id} {hhmm(f.interval.start)}: {f.reason}" for f in fixes))
        if a.fix_script:
            a.fix_script.write_text(fix_script(fixes), encoding="utf-8")
            print(f"\nwrote {a.fix_script}: review it, then `bash {a.fix_script}`")
        else:
            print("\nPass --fix-script PATH to write them as a script.")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
