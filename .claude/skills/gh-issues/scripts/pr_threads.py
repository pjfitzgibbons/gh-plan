#!/usr/bin/env python3
"""Review threads on a PR: list them, or turn replies into a paced reply-and-resolve script.

    pr_threads.py 73                                  # unresolved threads: comment id, path, first line
    pr_threads.py 73 --all                            # resolved ones too
    pr_threads.py 73 --replies .tmp/pr-73-replies.tsv > .tmp/reply-73.sh
    pr_threads.py 73 --post .tmp/79/replies           # post each <comment id>.md, resolve, delete it

The replies file is TSV: the review comment id (from the listing), a tab, the reply text. Each
reply is posted to its thread, then the thread is resolved. gh has no command for either, so the
script uses `gh api`: REST for the reply, GraphQL `resolveReviewThread` for the resolve.

--post, which pr runs after its push, does the same from a folder of <comment id>.md files, one
reply each, and deletes each file once its thread is resolved. Every file is checked before the
first post. It is safe to repeat: a reply the thread already has from you is not posted again.
"""

import argparse
import subprocess
import sys
import time
from pathlib import Path
from shlex import quote

sys.path.insert(0, str(Path(__file__).parent))
from ghread import gh_json  # noqa: E402

QUERY = """query($owner:String!,$name:String!,$pr:Int!){repository(owner:$owner,name:$name){
pullRequest(number:$pr){reviewThreads(first:100){nodes{id isResolved
comments(first:100){nodes{databaseId path line originalLine author{login} body}}}}}}}"""


def gh_write(args: list[str]) -> None:
    """A gh call that writes; a failure stops the run, naming it, with what was done so far printed."""
    result = subprocess.run(["gh", *args], capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"gh failed: gh {' '.join(args[:2])}\n{result.stderr.strip()}")


def repo_name(repo: str | None) -> str:
    return repo or gh_json(["repo", "view", "--json", "nameWithOwner"])["nameWithOwner"]


def threads(repo: str, pr: int) -> list[dict]:
    owner, name = repo.split("/")
    data = gh_json(["api", "graphql", "-f", f"query={QUERY}", "-F", f"owner={owner}",
                    "-F", f"name={name}", "-F", f"pr={pr}"])
    out = []
    for t in data["data"]["repository"]["pullRequest"]["reviewThreads"]["nodes"]:
        c, *rest = t["comments"]["nodes"]
        out.append({"thread": t["id"], "resolved": t["isResolved"], "comment": c["databaseId"],
                    "path": c["path"], "line": c["line"] or c["originalLine"],
                    "author": (c["author"] or {}).get("login"), "body": c["body"],
                    "replies": [((r["author"] or {}).get("login"), r["body"]) for r in rest]})
    return out


def read_replies(text: str) -> list[tuple[int, str]]:
    replies = []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        cid, sep, reply = line.partition("\t")
        if not sep or not cid.strip().isdigit() or not reply.strip():
            raise ValueError(f"line {n}: expected <comment id><TAB><reply>")
        replies.append((int(cid), reply.strip()))
    return replies


def emit(repo: str, pr: int, found: list[dict], replies: list[tuple[int, str]], pause: float = 1.0) -> str:
    by_comment = {t["comment"]: t for t in found}
    lines = ["#!/usr/bin/env bash", "# Generated by gh-issues pr_threads.py. Review before running.",
             "set -euo pipefail", "export GH_PAGER=cat", ""]
    for i, (cid, reply) in enumerate(replies):
        t = by_comment.get(cid)
        if t is None:
            raise ValueError(f"comment {cid} does not start a review thread on #{pr}")
        if i:
            lines.append(f"sleep {pause:g}")
        lines.append(f"# {t['path']}:{t['line']}")
        lines.append(f"gh api repos/{repo}/pulls/{pr}/comments/{cid}/replies -f body={quote(reply)} --silent")
        lines.append(f"sleep {pause:g}")
        lines.append("gh api graphql -f query='mutation($id:ID!){resolveReviewThread(input:{threadId:$id})"
                     f"{{thread{{isResolved}}}}}}' -f id={t['thread']} --silent")
    return "\n".join(lines) + "\n"


def read_reply_dir(folder: Path, pr: int, found: list[dict]) -> list[tuple[Path, dict, str]]:
    """Each <comment id>.md in folder with its thread and reply; ValueError naming the first bad one."""
    by_comment = {t["comment"]: t for t in found}
    out = []
    for f in sorted(folder.glob("*.md")):
        if not f.stem.isdigit():
            raise ValueError(f"{f}: name it <comment id>.md, from pr_threads.py {pr}")
        t = by_comment.get(int(f.stem))
        if t is None:
            raise ValueError(f"{f}: comment {f.stem} does not start a review thread on #{pr}")
        reply = f.read_text(encoding="utf-8").strip()
        if not reply:
            raise ValueError(f"{f} is empty")
        out.append((f, t, reply))
    return out


def post(repo: str, pr: int, me: str, pending: list[tuple[Path, dict, str]], api=gh_write, pause: float = 1.0) -> None:
    """Posts each reply the thread lacks, resolves the thread, then deletes the file, printing each
    write as it lands, so a run stopped part way says what it did."""
    for i, (f, t, reply) in enumerate(pending):
        where = f"{t['path']}:{t['line']}"
        if (me, reply) not in [(a, b.strip()) for a, b in t["replies"]]:
            if i:
                time.sleep(pause)
            api(["api", f"repos/{repo}/pulls/{pr}/comments/{t['comment']}/replies", "-f", f"body={reply}", "--silent"])
            print(f"pr: replied on {where}", flush=True)
        if not t["resolved"]:
            time.sleep(pause)
            api(["api", "graphql", "-f", "query=mutation($id:ID!){resolveReviewThread(input:{threadId:$id})"
                 "{thread{isResolved}}}", "-f", f"id={t['thread']}", "--silent"])
            print(f"pr: resolved {where}", flush=True)
        f.unlink()


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("pr", type=int)
    p.add_argument("--repo")
    p.add_argument("--all", action="store_true", help="include resolved threads")
    p.add_argument("--replies", type=Path, help="TSV of comment id and reply; prints a script")
    p.add_argument("--post", type=Path, help="folder of <comment id>.md replies; posts, resolves and deletes each")
    a = p.parse_args(argv)
    repo = repo_name(a.repo)
    found = threads(repo, a.pr)
    if a.post:
        try:
            pending = read_reply_dir(a.post, a.pr, found)
        except ValueError as e:
            sys.exit(f"pr_threads.py: {e}; nothing posted")
        me = gh_json(["api", "user"])["login"]
        post(repo, a.pr, me, pending)
        if a.post.is_dir() and not any(a.post.iterdir()):
            a.post.rmdir()
        return 0
    if a.replies:
        try:
            print(emit(repo, a.pr, found, read_replies(a.replies.read_text(encoding="utf-8"))), end="")
        except ValueError as e:
            sys.exit(f"pr_threads.py: {e}")
        return 0
    shown = [t for t in found if a.all or not t["resolved"]]
    for t in shown:
        first = t["body"].strip().splitlines()[0] if t["body"].strip() else ""
        state = "resolved" if t["resolved"] else "open"
        print(f"{t['comment']}\t{state}\t{t['path']}:{t['line']}\t{t['author']}\t{first[:100]}")
    if not shown:
        print("no unresolved threads" if not a.all else "no review threads")
    return 0


if __name__ == "__main__":
    sys.exit(main())
